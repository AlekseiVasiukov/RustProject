// ℹ️  This file contains all the shared data structures used across our project.
//     Think of it as the "contract" defining what data looks like.
//
//     Each struct is a custom data type, like a blueprint for a packet of information.
//     We use derive macros (like #[derive(Debug, Serialize)]) to automatically
//     implement common behavior (printing, JSON conversion, etc.).

// Import traits for JSON serialization and OpenAPI documentation
use serde::{Deserialize, Serialize};
use utoipa::ToSchema;
use chrono::{DateTime, Utc};

// ============================================================================
// GameQueryRequest - The request we send to our GameEngine API
// ============================================================================

/// Represents a query request sent to the game engine.
/// 
/// This struct holds the prompt that will be forwarded to the LLM.
/// The `#[derive(...)]` lines automatically generate code for:
/// - Clone: Allows copying this struct
/// - Debug: Allows printing with {:?} for logging
/// - Serialize: Converts this struct TO JSON
/// - Deserialize: Converts JSON INTO this struct
/// - ToSchema: Generates OpenAPI/Swagger documentation automatically
#[derive(Debug, Clone, Serialize, Deserialize, ToSchema)]
pub struct GameQueryRequest {
    /// The prompt text to send to the LLM model.
    /// 
    /// Example: "What should the player do next?"
    pub prompt: String,
    
    /// Optional custom system message for the LLM.
    /// 
    /// If not provided, a default system prompt is used.
    #[serde(default)]
    pub system_message: Option<String>,
}

// ============================================================================
// GameQueryResponse - The response we return from our GameEngine API
// ============================================================================

/// Represents the response from the game engine after processing a query.
/// 
/// This contains the LLM's answer along with metadata about the request.
#[derive(Debug, Clone, Serialize, Deserialize, ToSchema)]
pub struct GameQueryResponse {
    /// The response text generated by the LLM model.
    pub content: String,
    
    /// Whether this request was successful or failed.
    /// 
    /// In our simulation, every 3rd request will have this set to `false`.
    pub success: bool,
    
    /// A timestamp showing when this response was created.
    /// 
    /// Using `DateTime<Utc>` gives us ISO 8601 formatted timestamps.
    #[serde(with = "chrono::serde::ts_seconds")]
    pub timestamp: DateTime<Utc>,
    
    /// An optional error message if the request failed.
    /// 
    /// This is `None` when the request succeeds.
    pub error: Option<String>,
}

// ============================================================================
// HealthStatus - Simple health check response
// ============================================================================

/// A simple response for the /health endpoint.
/// 
/// Used to check if the server is running and responsive.
#[derive(Debug, Clone, Serialize, Deserialize, ToSchema)]
pub struct HealthStatus {
    /// Always returns "ok" when the server is running.
    /// 
    /// If this endpoint returns an error, the server is unhealthy.
    pub status: String,
    
    /// A friendly message confirming the service is available.
    pub message: String,
    
    /// Current server timestamp.
    #[serde(with = "chrono::serde::ts_seconds")]
    pub timestamp: DateTime<Utc>,
}

// ============================================================================
// QueueMessage - Commands sent through the channel queue
// ============================================================================

/// Represents a command sent through the async channel queue.
/// 
/// This is an "enum" (enumeration), which is like a box that can hold
/// one of several possible types of values. In our case:
/// - Query: Process a game query request
/// - Shutdown: Stop the queue worker gracefully
#[derive(Debug)]
pub enum QueueMessage {
    /// Process a game query request.
    /// 
    /// Contains the request data and a channel to send the response back.
    /// The `tokio::sync::oneshot::Sender` is like a one-way pipe for results.
    Query {
        request: GameQueryRequest,
        response_sender: tokio::sync::oneshot::Sender<GameQueryResponse>,
    },
    
    /// Signal the queue worker to shut down.
    /// 
    /// This is sent when the server is stopping to ensure clean shutdown.
    Shutdown,
}